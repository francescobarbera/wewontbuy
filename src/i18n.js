export function normalizeLocale(locale) {
  return String(locale || "").toLowerCase().split("-")[0];
}

export function isSupportedLocale(locale) {
  return SUPPORTED_LOCALES.includes(locale);
}

export function detectBrowserLocale() {
  const browserLocales =
    typeof navigator !== "undefined" && navigator.languages?.length
      ? navigator.languages
      : typeof navigator !== "undefined" && navigator.language
        ? [navigator.language]
        : [];

  return browserLocales.map(normalizeLocale).find(isSupportedLocale) || DEFAULT_LOCALE;
}

export function loadInitialLocale(storage = globalThis.localStorage) {
  const savedLocale = storage?.getItem(LOCALE_KEY);
  if (isSupportedLocale(savedLocale)) return savedLocale;
  return detectBrowserLocale();
}

export function lookup(locale, key) {
  return key.split(".").reduce((value, segment) => value?.[segment], translations[locale]);
}

export function t(locale, key, params = {}) {
  const value = lookup(locale, key) ?? lookup(DEFAULT_LOCALE, key) ?? key;
  if (typeof value !== "string") return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}
